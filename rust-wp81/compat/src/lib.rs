/// Calls `QueryPerformanceCounter` directly, with no Rust clock machinery involved. Used by the
/// step-wise probe to separate "the raw Win32 call works" from "Rust's `Instant` works".
#[no_mangle]
pub unsafe extern "system" fn wp81_raw_qpc() -> i64 {
    // Resolved the same way as everything else rather than declared as another extern: a bare
    // extern here would be an unresolved symbol at link time, because std's own declaration was
    // replaced by a trampoline and there is no import library to borrow it from.
    // Built from a byte literal rather than a hand-written UTF-16 array: the previous version
    // had the wrong length and no terminator, so LoadLibraryExW simply failed.
    let mut wide = [0u16; 64];
    let name = b"api-ms-win-core-profile-l1-1-0.dll";
    for (i, &b) in name.iter().enumerate() {
        wide[i] = b as u16;
    }
    let p = wp81_resolve(wide.as_ptr(), b"QueryPerformanceCounter\0".as_ptr());
    if p.is_null() {
        return -1;
    }
    let f: unsafe extern "system" fn(*mut i64) -> i32 = core::mem::transmute(p);
    let mut v: i64 = 0;
    f(&mut v);
    v
}

/// WP8.1 exports this name from `api-ms-win-core-profile-l1-1-0`, but the value it returns cannot
/// be trusted - so this replaces std's binding rather than wrapping it.
///
/// `std`'s `perf_counter::frequency_init` is:
///
/// ```text
/// let mut frequency = 0;
/// cvt(c::QueryPerformanceFrequency(&mut frequency)).unwrap();
/// assert_unchecked(frequency != 0);
/// ```
///
/// `cvt(..).unwrap()` **panics** if the call reports failure, and with `panic = "abort"` a panic is
/// 0xC0000409. A zero frequency is no better: it survives into `NANOS_PER_SEC / frequency`, an
/// integer division by zero, which panics too. Either way the process dies.
///
/// The reason this is so hard to localise from a log is that `frequency_init` is `#[cold]` and
/// reached lazily. `Instant::now()` only needs `QueryPerformanceCounter` (which works, as the raw
/// QPC probe shows) - it is `elapsed()` that needs the frequency, and so the first call that asks
/// for a *duration* is the one that takes the process down.
///
/// So: ask the platform, believe it only if it both succeeds and reports a sane number, and
/// otherwise measure the rate against `GetSystemTimeAsFileTime`, which is always 100 ns units. The
/// measurement is self-calibrating - it cannot produce a wrong frequency, only a slightly
/// imprecise one - and it happens at most once.
#[no_mangle]
pub unsafe extern "system" fn QueryPerformanceFrequency(out: *mut i64) -> i32 {
    if out.is_null() {
        return 0;
    }

    let profile = b"api-ms-win-core-profile-l1-1-0.dll\0";
    let synch = b"api-ms-win-core-synch-l1-2-0.dll\0";
    let sysinfo = b"api-ms-win-core-sysinfo-l1-1-0.dll\0";

    // 1. The platform's own answer, when it has a usable one.
    let real = wp81_resolve_in(profile, b"QueryPerformanceFrequency\0".as_ptr());
    if !real.is_null() {
        let f: unsafe extern "system" fn(*mut i64) -> i32 = core::mem::transmute(real);
        let mut v: i64 = 0;
        if f(&mut v) != 0 && v > 0 {
            *out = v;
            return 1;
        }
    }

    // 2. Measure it. Both endpoints come from the same pair of clocks, so any constant offset
    //    cancels and only the ratio over the interval matters.
    let ft = wp81_resolve_in(sysinfo, b"GetSystemTimeAsFileTime\0".as_ptr());
    let qpc = wp81_resolve_in(profile, b"QueryPerformanceCounter\0".as_ptr());
    if ft.is_null() || qpc.is_null() {
        // 3. Nothing to measure with. 10 MHz is the tick rate Windows has reported since XP, and
        //    it is also what a 100 ns FILETIME clock implies.
        *out = 10_000_000;
        return 1;
    }

    let get_ft: unsafe extern "system" fn(*mut u64) = core::mem::transmute(ft);
    let get_qpc: unsafe extern "system" fn(*mut i64) -> i32 = core::mem::transmute(qpc);

    let mut t0: u64 = 0;
    let mut q0: i64 = 0;
    get_ft(&mut t0);
    get_qpc(&mut q0);

    // Sleep rather than spin: the two samples only need to be far enough apart for the ratio to
    // be accurate, and this costs no battery.
    let sleep = wp81_resolve_in(synch, b"Sleep\0".as_ptr());
    if !sleep.is_null() {
        let s: unsafe extern "system" fn(u32) = core::mem::transmute(sleep);
        s(100);
    }

    let mut t1: u64 = 0;
    let mut q1: i64 = 0;
    get_ft(&mut t1);
    get_qpc(&mut q1);

    let dt = t1.wrapping_sub(t0) as i64; // 100 ns units
    let dq = q1.wrapping_sub(q0);        // QPC ticks

    if dt <= 0 || dq <= 0 {
        *out = 10_000_000;
        return 1;
    }

    // 64-bit division is NOT available to us. LLVM lowers `i64 / i64` on this target to
    // `__rt_sdiv64`, an MSVC runtime helper that returns the quotient in r0:r1 *and* the remainder
    // in r2:r3 - a shape Rust cannot express, because a 16-byte aggregate is returned through a
    // hidden pointer instead. (The same reason compat implements `__rt_udiv` but deliberately not
    // `__rt_udiv64`.) Calling it would be an ABI mismatch, so the arithmetic is arranged to stay
    // inside 32 bits instead.
    //
    // The reduction is lossless for our purposes: over a 100 ms window `dt` is 1e6 units and `dq`
    // is ~1e6 even at a 100 MHz tick rate, so both fit u32 comfortably, `dq / dt_ms` is ~1e4, and
    // the final *1000 lands on ~1e7 - still inside u32.
    if dt > u32::MAX as i64 || dq > u32::MAX as i64 {
        *out = 10_000_000;
        return 1;
    }

    let dt_ms = (dt as u32) / 10_000; // 100 ns units -> milliseconds; __rt_udiv, which we have
    if dt_ms == 0 {
        *out = 10_000_000;
        return 1;
    }

    let freq = ((dq as u32) / dt_ms) as u64 * 1000;

    *out = if freq > 0 { freq as i64 } else { 10_000_000 };
    1
}

/// The CRT's at-exit registry. Nothing here registers an at-exit handler, so accepting the
/// registration and never running it is honest rather than merely convenient - the alternative
/// would be pulling the whole CRT back in, which re-imports KERNEL32.dll.
#[no_mangle]
pub unsafe extern "C" fn atexit(_func: *const c_void) -> i32 {
    0
}

// ===========================================================================
// Raw CreateThread probe.
//
// Rust's `std::thread::spawn` is `Builder::new().spawn(f).expect("failed to spawn thread")`, so
// an abort there means `CreateThread` returned 0. This calls `CreateThread` directly - no Rust
// thread machinery - so we can tell "the OS refuses to create threads" apart from "Rust's wrapper
// trips over something".
//
// Returns:  1 = thread created, ran and was joined
//          -1 = CreateThread failed; the low bits carry GetLastError
//          -2 = thread created but WaitForSingleObject timed out
//        -100 = CreateThread could not be resolved
// ===========================================================================

unsafe fn wp81_resolve_in(dll: &[u8], name: *const u8) -> *mut c_void {
    let mut wide = [0u16; 64];
    for (i, &b) in dll.iter().enumerate() {
        if i < 63 {
            wide[i] = b as u16;
        }
    }
    wp81_resolve(wide.as_ptr(), name)
}

#[no_mangle]
pub unsafe extern "system" fn wp81_raw_createthread() -> i64 {
    unsafe extern "system" fn proc(_ctx: *mut c_void) -> u32 {
        0
    }

    let ct = wp81_resolve_in(b"api-ms-win-core-processthreads-l1-1-2.dll\0", b"CreateThread\0".as_ptr());
    if ct.is_null() {
        return -100;
    }
    let create: unsafe extern "system" fn(*const c_void, usize,
                                          Option<unsafe extern "system" fn(*mut c_void) -> u32>,
                                          *mut c_void, u32, *mut u32) -> HANDLE =
        core::mem::transmute(ct);

    let h = create(core::ptr::null(), 0, Some(proc), core::ptr::null_mut(), 0,
                   core::ptr::null_mut());
    if h.is_null() {
        let gle = wp81_resolve_in(b"api-ms-win-core-errorhandling-l1-1-2.dll\0",
                                  b"GetLastError\0".as_ptr());
        let err = if gle.is_null() {
            0u32
        } else {
            let g: unsafe extern "system" fn() -> u32 = core::mem::transmute(gle);
            g()
        };
        return -1 - (err as i64) * 1000;
    }

    let wait = wp81_resolve_in(b"api-ms-win-core-synch-l1-2-0.dll\0", b"WaitForSingleObject\0".as_ptr());
    let result = if wait.is_null() {
        -2
    } else {
        let w: unsafe extern "system" fn(HANDLE, u32) -> u32 = core::mem::transmute(wait);
        if w(h, 5000) == 0 { 1 } else { -2 }
    };

    let close = wp81_resolve_in(b"api-ms-win-core-handle-l1-1-0.dll\0", b"CloseHandle\0".as_ptr());
    if !close.is_null() {
        let c: unsafe extern "system" fn(HANDLE) -> i32 = core::mem::transmute(close);
        c(h);
    }
    result
}

// ===========================================================================
// Parameterised CreateThread probe.
//
// `wp81_raw_createthread` above proved the OS will make a thread, but its routine returned
// immediately - so it says nothing about what Rust's `thread_start` does once it is *running*.
// That routine, in `std/src/sys/thread/windows.rs`, does three things before the user closure:
//
//     let init = Box::from_raw(data as *mut ThreadInit);
//     let rust_start = init.init();      // (a) TLS: set_current / with_current_name
//     stack_overflow::reserve_stack();   // (b) SetThreadStackGuarantee - and the compat
//                                        //     trampoline for it calls LoadLibraryExW +
//                                        //     GetProcAddress *from this new thread*
//     rust_start();                      // (c) catch_unwind + the closure
//
// This takes std's exact arguments (2 MiB reservation, STACK_SIZE_PARAM_IS_A_RESERVATION) and
// lets the routine perform one of those operations, so a single device run says which is fatal.
//
// Returns a small positive code identifying how far it got, or a negative error:
//        0x10      mode 0: entered and returned
//        0x11      mode 1: TLS set and read back correctly
//        0x12      mode 2: the lazy resolver worked from this thread
//        0x13      mode 3: a >4 KiB stack frame (i.e. __chkstk) worked
//        0x14      mode 4: SetThreadStackGuarantee succeeded
//        0xE1..E7  the corresponding step failed
//        -1 - err*1000   CreateThread failed
//        -2       the thread did not finish within 5 s
//        -100     CreateThread could not be resolved
// ===========================================================================

static PROBE_MODE: core::sync::atomic::AtomicU32 = core::sync::atomic::AtomicU32::new(0);
static PROBE_TLS_INDEX: core::sync::atomic::AtomicU32 =
    core::sync::atomic::AtomicU32::new(0xFFFF_FFFF);
static PROBE_RESULT: core::sync::atomic::AtomicU32 = core::sync::atomic::AtomicU32::new(0);

const PROC_THREADS: &[u8] = b"api-ms-win-core-processthreads-l1-1-2.dll\0";

unsafe extern "system" fn wp81_probe_thread_proc(_ctx: *mut c_void) -> u32 {
    use core::sync::atomic::Ordering;
    let mode = PROBE_MODE.load(Ordering::SeqCst);

    let r = match mode {
        // 0: enter and leave. Separates "std's CreateThread arguments are fine" from everything
        //    the routine subsequently does.
        0 => 0x10,

        // 1: TLS from the new thread, which is what `init.init()` -> `set_current` does first.
        //    The index is allocated on the main thread; this thread only reads and writes it.
        1 => {
            let idx = PROBE_TLS_INDEX.load(Ordering::SeqCst);
            let set = wp81_resolve_in(PROC_THREADS, b"TlsSetValue\0".as_ptr());
            let get = wp81_resolve_in(PROC_THREADS, b"TlsGetValue\0".as_ptr());
            if set.is_null() || get.is_null() {
                0xE1
            } else {
                let s: unsafe extern "system" fn(u32, *mut c_void) -> i32 =
                    core::mem::transmute(set);
                let g: unsafe extern "system" fn(u32) -> *mut c_void = core::mem::transmute(get);
                let sentinel = 0x5A5Au32 as usize as *mut c_void;
                if s(idx, sentinel) == 0 {
                    0xE2
                } else if g(idx) != sentinel {
                    0xE3
                } else {
                    0x11
                }
            }
        }

        // 2: the lazy resolver from a non-main thread. Every compat trampoline calls
        //    LoadLibraryExW + GetProcAddress on use, and `thread_start` reaches one of them
        //    immediately - so if re-entering the loader from a fresh thread is what WP8.1
        //    objects to, this is where it shows.
        2 => {
            let p = wp81_resolve_in(b"api-ms-win-core-profile-l1-1-0.dll\0",
                                    b"QueryPerformanceCounter\0".as_ptr());
            if p.is_null() { 0xE4 } else { 0x12 }
        }

        // 3: a stack frame larger than a page, which forces a call to __chkstk. That object is
        //    linked in by hand, so it is worth confirming it works off the main thread too.
        3 => {
            let mut big = [0u8; 8192];
            let mut i = 0usize;
            while i < big.len() {
                big[i] = (i & 0xFF) as u8;
                i += 1;
            }
            let mut acc = 0u32;
            let mut j = 0usize;
            while j < big.len() {
                acc = acc.wrapping_add(big[j] as u32);
                j += 1;
            }
            if acc == 0 { 0xE5 } else { 0x13 }
        }

        // 4: exactly what `stack_overflow::reserve_stack()` calls.
        4 => {
            let p = wp81_resolve_in(PROC_THREADS, b"SetThreadStackGuarantee\0".as_ptr());
            if p.is_null() {
                0xE6
            } else {
                let f: unsafe extern "system" fn(*mut u32) -> i32 = core::mem::transmute(p);
                let mut sz: u32 = 0x5000;
                if f(&mut sz) == 0 { 0xE7 } else { 0x14 }
            }
        }

        _ => 0xEF,
    };

    PROBE_RESULT.store(r, Ordering::SeqCst);
    r
}

#[no_mangle]
pub unsafe extern "system" fn wp81_raw_createthread_ex(flags: u32, stack: u32, mode: u32) -> i64 {
    use core::sync::atomic::Ordering;
    PROBE_MODE.store(mode, Ordering::SeqCst);
    PROBE_RESULT.store(0, Ordering::SeqCst);

    // TlsAlloc has to happen on a thread that already has a TLS block - this one - so that mode 1
    // tests *using* TLS from the new thread rather than allocating it there.
    if mode == 1 {
        let alloc = wp81_resolve_in(PROC_THREADS, b"TlsAlloc\0".as_ptr());
        if alloc.is_null() {
            return -200;
        }
        let a: unsafe extern "system" fn() -> u32 = core::mem::transmute(alloc);
        PROBE_TLS_INDEX.store(a(), Ordering::SeqCst);
    }

    let ct = wp81_resolve_in(PROC_THREADS, b"CreateThread\0".as_ptr());
    if ct.is_null() {
        return -100;
    }
    let create: unsafe extern "system" fn(*const c_void, usize,
                                          Option<unsafe extern "system" fn(*mut c_void) -> u32>,
                                          *mut c_void, u32, *mut u32) -> HANDLE =
        core::mem::transmute(ct);

    let h = create(core::ptr::null(), stack as usize, Some(wp81_probe_thread_proc),
                   core::ptr::null_mut(), flags, core::ptr::null_mut());
    if h.is_null() {
        let gle = wp81_resolve_in(b"api-ms-win-core-errorhandling-l1-1-2.dll\0",
                                  b"GetLastError\0".as_ptr());
        let err = if gle.is_null() {
            0u32
        } else {
            let g: unsafe extern "system" fn() -> u32 = core::mem::transmute(gle);
            g()
        };
        return -1 - (err as i64) * 1000;
    }

    let wait = wp81_resolve_in(b"api-ms-win-core-synch-l1-2-0.dll\0",
                               b"WaitForSingleObject\0".as_ptr());
    let joined = if wait.is_null() {
        false
    } else {
        let w: unsafe extern "system" fn(HANDLE, u32) -> u32 = core::mem::transmute(wait);
        w(h, 5000) == 0
    };

    let close = wp81_resolve_in(b"api-ms-win-core-handle-l1-1-0.dll\0", b"CloseHandle\0".as_ptr());
    if !close.is_null() {
        let c: unsafe extern "system" fn(HANDLE) -> i32 = core::mem::transmute(close);
        c(h);
    }

    if !joined {
        return -2;
    }
    // Read from the static rather than trusting the routine's return value: if it aborts, the
    // process is gone anyway, and if it succeeds the static is the only reliable channel.
    PROBE_RESULT.load(Ordering::SeqCst) as i64
}
