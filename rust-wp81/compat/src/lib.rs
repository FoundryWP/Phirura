/// Result of the ARM divide helpers: AAPCS returns a two-word struct in r0:r1, which is
/// exactly the convention MSVC's `__rt_udiv` uses (quotient in r0, remainder in r1).
#[repr(C)]
pub struct UdivResult {
    pub quotient: u32,
    pub remainder: u32,
}

/// 32-bit divide and remainder, computed WITHOUT the `/` and `%` operators.
///
/// This is the whole point of the function. Writing `numerator / denominator` here - which is what
/// the first version did - compiles straight back into a call to `__rt_udiv`, because this target
/// has no hardware divide, and so the helper called itself until the stack ran out. On the device
/// that surfaced as `0x800703E9` (ERROR_STACK_OVERFLOW), which is not a shape any of the usual
/// explanations fit: it is not a missing import, not a bad API set, and not a panic.
///
/// The failure hid for two rounds because the probe's tests all used literal operands, so LLVM
/// constant-folded them and never emitted the call at all. Every test "passed" while the code was
/// unusable. See the `black_box` note in `link-probe/src/lib.rs`.
///
/// Schoolbook restoring division, one bit at a time. `r` is always kept below `d`, so `r << 1`
/// cannot overflow - except when `d` has its top bit set, which is handled separately because then
/// the quotient is 0 or 1 anyway.
fn udivmod_u32(n: u32, d: u32) -> (u32, u32) {
    if d == 0 {
        return (0, n);
    }
    if d > 0x7FFF_FFFF {
        return if n >= d { (1, n - d) } else { (0, n) };
    }
    let mut q: u32 = 0;
    let mut r: u32 = 0;
    let mut i: u32 = 32;
    while i > 0 {
        i -= 1;
        r = (r << 1) | ((n >> i) & 1);
        if r >= d {
            r -= d;
            q |= 1u32 << i;
        }
    }
    (q, r)
}

#[no_mangle]
pub extern "C" fn __rt_udiv(numerator: u32, denominator: u32) -> UdivResult {
    if denominator == 0 {
        // The hardware would trap; returning the numerator matches the ARM runtime's
        // documented behaviour for the divide-by-zero case closely enough to avoid UB.
        return UdivResult { quotient: 0, remainder: numerator };
    }
    let (q, r) = udivmod_u32(numerator, denominator);
    UdivResult { quotient: q, remainder: r }
}

/// 64-bit divide, same reasoning as `__rt_udiv`.
///
/// Superseded by the assembly version below, which is the only way to supply the remainder half.
/// Kept as a named reference in case the assembly is ever dropped.
#[allow(dead_code)]
fn udiv64_quotient_only(numerator: u64, denominator: u64) -> u64 {
    if denominator == 0 {
        return 0;
    }
    udivmod_u64(numerator, denominator).0
}

/// 64-bit divide and remainder without `/` or `%`.
///
/// Also exported: a Rust-to-Rust escape hatch for anything that needs both halves without going
/// near the MSVC helper. Rust-to-Rust calls use one consistent convention for the returned pair,
/// so unlike `__rt_udiv64` there is nothing to guess at.
fn udivmod_u64(n: u64, d: u64) -> (u64, u64) {
    if d == 0 {
        return (0, n);
    }
    if d > 0x7FFF_FFFF_FFFF_FFFF {
        return if n >= d { (1, n - d) } else { (0, n) };
    }
    let mut q: u64 = 0;
    let mut r: u64 = 0;
    let mut i: u32 = 64;
    while i > 0 {
        i -= 1;
        r = (r << 1) | ((n >> i) & 1);
        if r >= d {
            r -= d;
            q |= 1u64 << i;
        }
    }
    (q, r)
}

// ===========================================================================
// Signed 64-bit divide, and the float <-> integer conversions.
//
// All of these are MSVC ARM runtime helpers that a /NODEFAULTLIB link has to supply. They share one
// trap, and it is the trap that cost this project the most time: **a helper must not use the
// operation it implements.** `__rt_udiv64` was written as `numerator / denominator` and called
// itself until the stack died; writing `d as i64` here would do exactly the same thing, because on
// this target every one of these operations lowers to a call to its own helper.
//
// The conversions are therefore forwarded to `compiler_builtins`, which implements them with
// integer bit manipulation precisely so that they do not recurse. It is already linked as part of
// build-std, so this costs nothing.
// ===========================================================================

