// ===========================================================================
// `__rt_udiv64` - the one runtime helper that cannot be written in Rust.
//
// MSVC's ARM helper returns a 16-byte result in registers: the quotient in r0:r1 *and* the
// remainder in r2:r3, so one call serves both `/` and `%`. Rust cannot express that - a 16-byte
// aggregate comes back through a hidden pointer instead - so this has to be assembly.
//
// The convention below was read off LLVM's own output, not from documentation. Compiling
// `fn div64(a: u64, b: u64) -> u64 { a / b }` and `fn rem64(a: u64, b: u64) -> u64 { a % b }` for
// this target gives:
//
//     div64:                          rem64:
//       mov  lr,  r0                    mov  r12, r1
//       mov  r12, r1                    mov  r0,  r2     <- divisor
//       mov  r0,  r2   <- divisor       mov  r1,  r3
//       mov  r1,  r3                    mov  r2,  lr     <- dividend
//       mov  r2,  lr   <- dividend      mov  r3,  r12
//       mov  r3,  r12                   bl   __rt_udiv64
//       bl   __rt_udiv64                mov  r0,  r2     <- REMAINDER
//       pop  {r11, pc}  (r0:r1 = quot)  mov  r1,  r3
//
// So the arguments arrive as r0:r1 = divisor and r2:r3 = dividend - the divisor FIRST, which is
// the opposite of the obvious reading - and the answer is dividend / divisor.
//
// ARM has no 64-bit divide instruction, which is why adding `+hwdiv` to the target spec removes
// this helper for 32-bit division (LLVM emits `udiv`) but not for 64-bit. Note also that
// compiler_builtins calls it internally, so it is not avoidable by patching std alone.
//
// The routine is schoolbook restoring division: 64 iterations, no division instruction anywhere.
// That is also what stops the previous Rust version - written as `numerator / denominator` - from
// calling itself until the stack ran out.
// ===========================================================================
core::arch::global_asm!(
    r#"
    .syntax unified
    .thumb
    .text
    .globl __rt_udiv64
    .thumb_func
__rt_udiv64:
    push    {{r4, r5, r6, r7, r8, lr}}

    mov     r4, r2          @ n_lo = dividend low
    mov     r5, r3          @ n_hi = dividend high
    mov     r6, r0          @ d_lo = divisor low
    mov     r7, r1          @ d_hi = divisor high

    movs    r0, #0          @ q = 0
    movs    r1, #0
    movs    r2, #0          @ r = 0
    movs    r3, #0
    mov.w   r8, #64

.Ludiv64_loop:
    @ n <<= 1, leaving the outgoing MSB in C
    lsls    r4, r4, #1
    adcs    r5, r5, r5
    @ r = (r << 1) | C
    adcs    r2, r2, r2
    adcs    r3, r3, r3
    @ q <<= 1
    lsls    r0, r0, #1
    adcs    r1, r1, r1
    @ if r >= d, then r -= d and set the low bit of q
    cmp     r3, r7
    bhi     .Ludiv64_sub
    blo     .Ludiv64_next
    cmp     r2, r6
    blo     .Ludiv64_next
.Ludiv64_sub:
    subs    r2, r2, r6
    sbcs    r3, r3, r7
    @ bit 0 of q is known to be clear after the shift, so this is an OR in effect, and `adds` is
    @ certain to encode as a 16-bit instruction where `orrs rd, rd, #1` is not
    adds    r0, r0, #1
.Ludiv64_next:
    subs.w  r8, r8, #1
    bne     .Ludiv64_loop

    pop     {{r4, r5, r6, r7, r8, pc}}
"#
);

// ===========================================================================
// `__rt_sdiv64` - signed 64-bit divide.
//
// Same ABI as `__rt_udiv64`: r0:r1 = divisor, r2:r3 = dividend; r0:r1 = quotient, r2:r3 = remainder.
// Also assembly for the same reason - a 16-byte register return cannot be expressed in Rust.
//
// The sign handling is done by taking absolute values, calling the unsigned routine, and re-applying
// the signs: the quotient is negative when the operands' signs differ, and the remainder always
// takes the dividend's sign (that is what C's `/` and `%` specify, and `prpr` relies on it for
// chart time arithmetic).
// ===========================================================================
core::arch::global_asm!(
    r#"
    .syntax unified
    .thumb
    .text
    .globl __rt_sdiv64
    .thumb_func
__rt_sdiv64:
    push    {{r4, r5, r6, lr}}

    @ r4 = sign of dividend, r5 = sign of divisor
    movs    r4, #0
    cmp     r3, #0
    bpl     .Lsdiv_n_pos
    movs    r4, #1
    mvns    r2, r2
    mvns    r3, r3
    adds    r2, r2, #1
    adcs    r3, r3, #0
.Lsdiv_n_pos:
    movs    r5, #0
    cmp     r1, #0
    bpl     .Lsdiv_d_pos
    movs    r5, #1
    mvns    r0, r0
    mvns    r1, r1
    adds    r0, r0, #1
    adcs    r1, r1, #0
.Lsdiv_d_pos:
    bl      __rt_udiv64

    @ quotient is negative when the signs differ
    cmp     r4, r5
    beq     .Lsdiv_q_pos
    mvns    r0, r0
    mvns    r1, r1
    adds    r0, r0, #1
    adcs    r1, r1, #0
.Lsdiv_q_pos:
    @ the remainder takes the dividend's sign
    cmp     r4, #0
    beq     .Lsdiv_r_pos
    mvns    r2, r2
    mvns    r3, r3
    adds    r2, r2, #1
    adcs    r3, r3, #0
.Lsdiv_r_pos:
    pop     {{r4, r5, r6, pc}}
"#
);



