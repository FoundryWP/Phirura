//! WP8.1 implementations of the Win32 entry points `std` needs but the platform lacks.
//!
//! `wp81_std_patch.py` rewrites the 19 `windows_link::link!(...)` declarations for these
//! symbols into plain `unsafe extern "system"` blocks, so they stop being `raw-dylib` imports
//! bound to `ntdll.dll` / `kernel32.dll` and become ordinary undefined symbols. This crate
//! defines them.
//!
//! Everything here is built on the WP8.1 API set, which is defined by the import libs in
//! `Windows Phone Kits\8.1\lib\ARM\`. The relevant ones:
//!
//!   api-ms-win-core-file-l1-2-1   CreateFileW, ReadFile, WriteFile, SetFilePointerEx,
//!                                 SetFileInformationByHandle, SetEndOfFile, ...
//!   api-ms-win-core-heap-l1-2-0   HeapAlloc, GetProcessHeap
//!   api-ms-win-core-synch-l1-2-0  WaitForSingleObject, ...
//!
//! # The NTSTATUS trick
//!
//! `std` calls these NT functions and converts failures with `RtlNtStatusToDosError`, then
//! hands the result to `io::Error::from_raw_os_error`. Rather than inventing NTSTATUS values
//! for every Win32 failure, the shims return the **Win32 error code unchanged** and
//! `RtlNtStatusToDosError` is the identity. `std` therefore sees exactly the error it would
//! have got from the Win32 call. This is why every failure path below returns `c_GetLastError()`.
//!
//! # What is not done yet
//!
//! * `NtCreateNamedPipeFile` — only used by `std::process` for child-process pipes, which
//!   WP8.1 cannot do at all. Returns `STATUS_NOT_IMPLEMENTED`.
//! * `NtSetInformationFile` handles the rename and disposition classes `std::fs` uses; other
//!   classes return `STATUS_NOT_IMPLEMENTED`.

#![no_std]
#![allow(non_snake_case, non_camel_case_types, clippy::missing_safety_doc)]

