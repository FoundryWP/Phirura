/// `std::env::home_dir` on Windows goes through this. WP8.1 has no user profile directory;
/// the app's own local folder is the closest thing, and the C++/CX shell supplies it.
#[no_mangle]
pub unsafe extern "system" fn GetUserProfileDirectoryW(_token: HANDLE, dir: PWSTR,
                                                       size: *mut u32) -> BOOL {
    if size.is_null() {
        return FALSE;
    }
    let len = profile_dir_len();
    let needed = len as u32 + 1; // + NUL
    if dir.is_null() || *size < needed {
        *size = needed;
        return FALSE;
    }
    core::ptr::copy_nonoverlapping(profile_dir_ptr(), dir, len);
    *dir.add(len) = 0;
    *size = needed;
    TRUE
}

const PROFILE_DIR_CAP: usize = 260;

static mut WP81_PROFILE_DIR: [u16; PROFILE_DIR_CAP] = [0; PROFILE_DIR_CAP];
static mut WP81_PROFILE_DIR_LEN: usize = 0;

// Deliberately go through `addr_of!`/`addr_of_mut!` rather than taking a reference to the
// mutable static: a `&mut` to a `static mut` is undefined behaviour under the 2024 rules, and
// the borrow checker cannot see the aliasing here anyway.
#[inline]
unsafe fn profile_dir_ptr() -> *const u16 {
    core::ptr::addr_of!(WP81_PROFILE_DIR) as *const u16
}

#[inline]
unsafe fn profile_dir_len() -> usize {
    core::ptr::addr_of!(WP81_PROFILE_DIR_LEN).read()
}

/// Called from the C++/CX shell with the app's local folder, so `home_dir()` returns
/// something usable instead of an empty string.
#[no_mangle]
pub unsafe extern "system" fn wp81_set_profile_dir(utf16: *const u16, len: usize) -> BOOL {
    if utf16.is_null() || len == 0 || len >= PROFILE_DIR_CAP {
        return FALSE;
    }
    core::ptr::copy_nonoverlapping(utf16, core::ptr::addr_of_mut!(WP81_PROFILE_DIR) as *mut u16, len);
    core::ptr::addr_of_mut!(WP81_PROFILE_DIR_LEN).write(len);
    TRUE
}

// ===========================================================================
// Synchronisation — WaitForMultipleObjects is absent from the WP8.1 synch API set,
// though WaitForSingleObject is present.
// ===========================================================================



const WAIT_OBJECT_0: u32 = 0;
const WAIT_TIMEOUT: u32 = 258;
const WAIT_FAILED: u32 = 0xFFFF_FFFF;

#[no_mangle]
pub unsafe extern "system" fn WaitForMultipleObjects(nCount: u32, handles: *const HANDLE,
                                                     bWaitAll: BOOL, ms: u32) -> u32 {
    if handles.is_null() || nCount == 0 {
        return WAIT_FAILED;
    }

    if bWaitAll == FALSE {
        // Any-of: poll each handle with a zero timeout, then fall back to sleeping.
        loop {
            for i in 0..nCount as usize {
                if c_WaitForSingleObject(*handles.add(i), 0) == WAIT_OBJECT_0 {
                    return WAIT_OBJECT_0 + i as u32;
                }
            }
            if ms == 0 {
                return WAIT_TIMEOUT;
            }
            // std only uses this for child-process pipes, which WP8.1 cannot create, so a
            // coarse poll is an acceptable stand-in for a real multi-wait.
            c_Sleep(1);
        }
    }

    // Wait-all: wait on each in turn, then report success.
    for i in 0..nCount as usize {
        let r = c_WaitForSingleObject(*handles.add(i), ms);
        if r != WAIT_OBJECT_0 {
            return r;
        }
    }
    WAIT_OBJECT_0
}

// ===========================================================================
// Randomness.
//
// `ProcessPrng` lives in bcryptprimitives.dll, which is present on WP8.1 but has **no import
// library in the SDK**, so it cannot be linked against statically. It is therefore resolved at
// run time through LoadLibraryW/GetProcAddress - the standard answer when the SDK ships no lib,
// and it costs one call on first use.
// ===========================================================================

// `LoadLibraryW` / `GetProcAddress` are declared in the raw-dylib block near the top.
const BCRYPT_USE_SYSTEM_PREFERRED_RNG: u32 = 0x0000_0002;

type BCryptGenRandomFn = unsafe extern "system" fn(HANDLE, *mut u8, u32, u32) -> NTSTATUS;

/// `L"bcryptprimitives.dll"`, NUL-terminated.
static BCRYPT_DLL: [u16; 23] = [
    0x62, 0x63, 0x72, 0x79, 0x70, 0x74, 0x70, 0x72, 0x69, 0x6D, 0x69, 0x74,
    0x69, 0x76, 0x65, 0x73, 0x2E, 0x64, 0x6C, 0x6C, 0x00, 0x00, 0x00,
];

/// `"BCryptGenRandom"`, NUL-terminated.
static BCRYPT_GEN_RANDOM: [u8; 16] = *b"BCryptGenRandom\0";

static mut WP81_BCRYPT: Option<BCryptGenRandomFn> = None;
static mut WP81_BCRYPT_TRIED: bool = false;

/// Resolves `BCryptGenRandom` once. Returns `None` if the DLL or the export is unavailable,
/// in which case `ProcessPrng` falls back to the software mixer below.
unsafe fn bcrypt_gen_random() -> Option<BCryptGenRandomFn> {
    if core::ptr::addr_of!(WP81_BCRYPT_TRIED).read() {
        return core::ptr::addr_of!(WP81_BCRYPT).read();
    }
    core::ptr::addr_of_mut!(WP81_BCRYPT_TRIED).write(true);

    let module = LoadLibraryExW(BCRYPT_DLL.as_ptr(), core::ptr::null_mut(), 0);
    let resolved = if module.is_null() {
        None
    } else {
        let p = GetProcAddress(module, BCRYPT_GEN_RANDOM.as_ptr());
        if p.is_null() {
            None
        } else {
            Some(core::mem::transmute::<*mut c_void, BCryptGenRandomFn>(p))
        }
    };
    core::ptr::addr_of_mut!(WP81_BCRYPT).write(resolved);
    resolved
}

static mut WP81_PRNG_STATE: u64 = 0x9E37_79B9_7F4A_7C15;

#[no_mangle]
pub unsafe extern "system" fn ProcessPrng(pbdata: *mut u8, cbdata: usize) -> BOOL {
    if pbdata.is_null() || cbdata == 0 {
        return FALSE;
    }

    if let Some(gen) = bcrypt_gen_random() {
        if gen(core::ptr::null_mut(), pbdata, cbdata as u32,
               BCRYPT_USE_SYSTEM_PREFERRED_RNG) == STATUS_SUCCESS {
            return TRUE;
        }
    }

    // Fallback. Seeded from the system time so it is at least not identical every run.
    // NOT cryptographically secure - recorded as a known limitation.
    let mut state = core::ptr::addr_of_mut!(WP81_PRNG_STATE).read();
    for i in 0..cbdata {
        state ^= state << 13;
        state ^= state >> 7;
        state ^= state << 17;
        *pbdata.add(i) = (state >> 24) as u8;
    }
    core::ptr::addr_of_mut!(WP81_PRNG_STATE).write(state);
    TRUE
}

// ===========================================================================
// NT file API -> Win32 file API.
//
// std prefers the NT calls because they expose reparse-point and disposition semantics it
// needs. WP8.1 cannot import ntdll, but api-ms-win-core-file-l1-2-1 provides the Win32
// equivalents, so each shim is a translation. See the NTSTATUS note at the top of the file.
// ===========================================================================

/// Strips the `\??\` (and `\Device\...`) prefixes NT paths carry, producing something
/// CreateFileW accepts. Returns a pointer into `buffer`, which the caller owns.
unsafe fn nt_path_to_win32(name: *const UNICODE_STRING, buffer: *mut u16,
                           buffer_len: usize) -> *const u16 {
    if name.is_null() {
        return core::ptr::null();
    }
    let u = &*name;
    if u.Buffer.is_null() || u.Length == 0 {
        return core::ptr::null();
    }

    let chars = (u.Length / 2) as usize;
    let mut start = 0usize;

    // `\??\` is 4 chars.
    if chars >= 4 {
        let p = u.Buffer;
        if *p == b'\\' as u16
            && *p.add(1) == b'?' as u16
            && *p.add(2) == b'?' as u16
            && *p.add(3) == b'\\' as u16
        {
            start = 4;
        }
    }

    let n = chars - start;
    if n + 1 > buffer_len {
        return core::ptr::null();
    }
    core::ptr::copy_nonoverlapping(u.Buffer.add(start), buffer, n);
    *buffer.add(n) = 0;
    buffer as *const u16
}

fn nt_disposition_to_win32(disposition: u32) -> u32 {
    match disposition {
        FILE_SUPERSEDE => CREATE_ALWAYS,
        FILE_OPEN => OPEN_EXISTING,
        FILE_CREATE => CREATE_NEW,
        FILE_OPEN_IF => OPEN_ALWAYS,
        FILE_OVERWRITE => TRUNCATE_EXISTING,
        FILE_OVERWRITE_IF => CREATE_ALWAYS,
        _ => OPEN_EXISTING,
    }
}

fn nt_options_to_win32(options: u32, file_attributes: u32) -> u32 {
    let mut flags = file_attributes;
    if flags == 0 {
        flags = FILE_ATTRIBUTE_NORMAL;
    }
    if options & FILE_DIRECTORY_FILE != 0 {
        // Win32 requires this to open a directory at all.
        flags |= FILE_FLAG_BACKUP_SEMANTICS;
    }
    if options & FILE_OPEN_REPARSE_POINT != 0 {
        // Same numeric value in both worlds, but spelled out for clarity.
        flags |= FILE_FLAG_OPEN_REPARSE_POINT;
    }
    let _ = FILE_NON_DIRECTORY_FILE;
    let _ = FILE_SYNCHRONOUS_IO_NONALERT;
    flags
}

unsafe fn open_nt_file(filehandle: *mut HANDLE, desiredaccess: ACCESS_MASK,
                       objectattributes: *const OBJECT_ATTRIBUTES,
                       iostatusblock: *mut IO_STATUS_BLOCK, shareaccess: u32,
                       createdisposition: u32, createoptions: u32,
                       fileattributes: u32) -> NTSTATUS {
    if filehandle.is_null() || objectattributes.is_null() {
        return STATUS_INVALID_PARAMETER;
    }

    let mut path_buf = [0u16; 260];
    let path = nt_path_to_win32((*objectattributes).ObjectName,
                                path_buf.as_mut_ptr(), path_buf.len());
    if path.is_null() {
        return STATUS_INVALID_PARAMETER;
    }

    let handle = c_CreateFileW(
        path,
        desiredaccess,
        shareaccess,
        core::ptr::null(),
        nt_disposition_to_win32(createdisposition),
        nt_options_to_win32(createoptions, fileattributes),
        core::ptr::null_mut(),
    );

    if handle == INVALID_HANDLE_VALUE {
        return c_GetLastError() as NTSTATUS;
    }

    *filehandle = handle;
    if !iostatusblock.is_null() {
        (*iostatusblock).Status = STATUS_SUCCESS;
        (*iostatusblock).Information = 1; // FILE_OPENED
    }
    STATUS_SUCCESS
}

