/// `std` uses this for rename (`FileRenameInformation`) and delete
/// (`FileDispositionInformation`), plus truncation. Both have Win32 equivalents.
#[no_mangle]
pub unsafe extern "system" fn NtSetInformationFile(filehandle: HANDLE,
                                                   iostatusblock: *mut IO_STATUS_BLOCK,
                                                   fileinformation: *const c_void, length: u32,
                                                   fileinformationclass: i32) -> NTSTATUS {
    if filehandle.is_null() || filehandle == INVALID_HANDLE_VALUE {
        return STATUS_INVALID_PARAMETER;
    }

    let ok = match fileinformationclass {
        FILE_DISPOSITION_INFORMATION_CLASS => {
            // Same layout: a single BOOLEAN.
            if length < 1 {
                return STATUS_INFO_LENGTH_MISMATCH;
            }
            c_SetFileInformationByHandle(filehandle, FILE_DISPOSITION_INFO_CLASS,
                                       fileinformation, 1)
        }
        FILE_RENAME_INFORMATION_CLASS => {
            if length < 12 {
                return STATUS_INFO_LENGTH_MISMATCH;
            }
            let info = fileinformation as *const FILE_RENAME_INFORMATION;
            // Win32's FILE_RENAME_INFO is { ReplaceIfExists: BOOLEAN, RootDirectory: HANDLE,
            // FileNameLength: DWORD, FileName[] } - the same shape, so it passes through.
            let name_bytes = (*info).FileNameLength as usize;
            let total = 8 + name_bytes;
            c_SetFileInformationByHandle(filehandle, FILE_RENAME_INFO_CLASS,
                                       fileinformation, total as u32)
        }
        FILE_END_OF_FILE_INFORMATION_CLASS => {
            if length < 8 {
                return STATUS_INFO_LENGTH_MISMATCH;
            }
            // FileEndOfFileInfo takes a single LARGE_INTEGER.
            c_SetFileInformationByHandle(filehandle, FILE_END_OF_FILE_INFO_CLASS,
                                       fileinformation, 8)
        }
        _ => return STATUS_NOT_IMPLEMENTED,
    };

    if ok == FALSE {
        return c_GetLastError() as NTSTATUS;
    }
    if !iostatusblock.is_null() {
        (*iostatusblock).Status = STATUS_SUCCESS;
        (*iostatusblock).Information = 0;
    }
    STATUS_SUCCESS
}

