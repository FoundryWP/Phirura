#!/usr/bin/env python3
"""Generate compat/src/generated_api.rs — runtime-resolved trampolines for the API-set imports.

Why
---
`std` binds ~143 Win32 functions to `kernel32.dll`. WP8.1 apps may not import that, so the
patcher re-points them at the API set that exports them. That works right up until one of the
hand-written set names is wrong **for the target platform** — and then the DLL fails to load:

    ERROR_PROC_NOT_FOUND (0x8007007F): "The specified procedure could not be found"

with no symbol named. Desktop Windows exports more than WP8.1, so `verify_mapping.py` can only
find definite errors, never prove correctness. That is exactly how this bit us.

So the declarations are emitted as **plain externs** instead, and this script generates a
trampoline per function that resolves it at run time:

    LoadLibraryW(api set) -> GetProcAddress(name) -> call through

A wrong name now becomes a logged null instead of a load-time failure.

ABI safety
----------
Every trampoline takes and returns `usize`. That is sound here because every parameter and
return in the set is integer- or pointer-class: the apparent exceptions are type aliases for
pointers (`PCSTR`, `LPINIT_ONCE`, `LPTHREAD_START_ROUTINE`) or enums (`FINDEX_INFO_LEVELS`,
`FILE_INFO_BY_HANDLE_CLASS`), both of which are integer class under AAPCS. There are no float
or by-value-struct parameters, and no float returns. **If a function with those ever appears,
it must be excluded here and handled by hand.**

Usage:
    python gen_api_trampolines.py            # write the file
    python gen_api_trampolines.py --check    # report only
"""

import argparse
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PATCHER = os.path.join(HERE, "wp81_std_patch.py")
OUT = os.path.join(HERE, "compat", "src", "generated_api.rs")

HEADER = '''// @generated by rust-wp81/gen_api_trampolines.py — do not edit by hand.
//
// Runtime-resolved trampolines for the Win32 functions `std` binds to kernel32.dll.
//
// Each one looks its target up with LoadLibraryW + GetProcAddress on first call and then calls
// through. The point is that a name which does not exist on the target platform yields a null
// pointer and a log line, instead of the whole DLL refusing to load with ERROR_PROC_NOT_FOUND.
//
// Every parameter and return is `usize`: see the ABI note in the generator.

#![allow(non_snake_case)]

use core::ffi::c_void;

extern "system" {
    fn LoadLibraryExW(lpLibFileName: *const u16, hFile: *mut c_void, dwFlags: u32) -> *mut c_void;
    fn GetProcAddress(hModule: *mut c_void, lpProcName: *const u8) -> *mut c_void;
}

/// Resolve a (dll, symbol) pair, caching nothing — the loader and its export cache already do
/// that, and a static cache would need synchronisation for no measurable gain at this call rate.
pub(crate) unsafe fn wp81_resolve(dll: *const u16, name: *const u8) -> *mut c_void {
    let h = LoadLibraryExW(dll, core::ptr::null_mut(), 0);
    if h.is_null() {
        wp81_note_missing(dll, name, 1);
        return core::ptr::null_mut();
    }
    let p = GetProcAddress(h, name);
    if p.is_null() {
        wp81_note_missing(dll, name, 2);
    }
    p
}

'''

FOOTER = '''
/// Number of trampolines that failed to resolve, and the first failure, for diagnostics.
static mut WP81_MISSING: u32 = 0;
static mut WP81_MISSING_DLL: *const u16 = core::ptr::null();
static mut WP81_MISSING_FN: *const u8 = core::ptr::null();
static mut WP81_MISSING_KIND: u32 = 0;

unsafe fn wp81_note_missing(dll: *const u16, name: *const u8, kind: u32) {
    if WP81_MISSING == 0 {
        WP81_MISSING_DLL = dll;
        WP81_MISSING_FN = name;
        WP81_MISSING_KIND = kind;
    }
    WP81_MISSING += 1;
}

/// Diagnostics for the app shell: how many API-set functions failed to resolve, and which was
/// first. Returns the count; the names are written into the two out-parameters.
#[no_mangle]
pub unsafe extern "system" fn wp81_api_failures(dll_out: *mut *const u16,
                                                fn_out: *mut *const u8,
                                                kind_out: *mut u32) -> u32 {
    if !dll_out.is_null() { *dll_out = WP81_MISSING_DLL; }
    if !fn_out.is_null() { *fn_out = WP81_MISSING_FN; }
    if !kind_out.is_null() { *kind_out = WP81_MISSING_KIND; }
    WP81_MISSING
}
'''


def wide(s):
    """Rust source for a NUL-terminated UTF-16 literal."""
    return "[" + ", ".join("0x%04X" % ord(c) for c in s) + ", 0x0000]"


def narrow(s):
    """Rust source for a NUL-terminated byte literal."""
    return 'b"' + s + '\\0"'


def count_params(args):
    """Number of top-level comma-separated parameters in `(a : T, b : U)`."""
    inner = args.strip()
    if inner.startswith("("):
        inner = inner[1:]
    if inner.endswith(")"):
        inner = inner[:-1]
    if not inner.strip():
        return 0
    depth = 0
    n = 1
    for ch in inner:
        if ch in "([<":
            depth += 1
        elif ch in ")]>":
            depth -= 1
        elif ch == "," and depth == 0:
            n += 1
    return n


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv[1:])

    spec = importlib.util.spec_from_file_location("wp81_std_patch", PATCHER)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)

    # Scan the whole library tree, not just windows_sys.rs: std declares a few of these in
    # c.rs and elsewhere, and the generator must see every one or a trampoline goes missing.
    sigs = []
    for root, _dirs, files in os.walk(m.SRC_LIBRARY):
        for f in files:
            if not f.endswith(".rs"):
                continue
            path = os.path.join(root, f)
            try:
                text = open(path, encoding="utf-8").read()
            except (UnicodeDecodeError, OSError):
                continue
            if "windows_link::link!" not in text:
                continue
            _, _changed, _remapped, found = m.rewrite(text)
            sigs.extend(found)

    print("trampolines to generate: %d (%d left to compat)" % (len(sigs), 0))

    # compat declares a handful of these itself (it needs them to implement the NT shims, and
    # it needs LoadLibraryW/GetProcAddress to resolve anything at all). Generating a trampoline
    # for the same name would be a duplicate symbol, so those are skipped here.
    own = set()
    own_file = os.path.join(HERE, "compat_own_fns.txt")
    if os.path.exists(own_file):
        own = {l.strip() for l in open(own_file, encoding="utf-8") if l.strip()}

    body = []
    seen = set()
    skipped = 0
    for name, dll, argstr, ret in sorted(sigs):
        if name in seen:
            continue
        if name in own:
            skipped += 1
            continue
        seen.add(name)
        n = count_params(argstr)
        params = ", ".join("a%d: usize" % i for i in range(n))
        call = ", ".join("a%d" % i for i in range(n))
        body.append(
            "#[no_mangle]\n"
            "pub unsafe extern \"system\" fn {name}({params}) -> usize {{\n"
            "    // Null-safe on purpose: an unresolved function used to be called anyway, which is a\n"
            "    // jump to address 0. Returning 0 degrades instead of aborting, and the failure is\n"
            "    // already recorded by wp81_resolve for wp81_probe_api_sets to report.\n"
            "    let p = wp81_resolve({dll}.as_ptr(), {fnname}.as_ptr());\n"
            "    if p.is_null() {{ return 0; }}\n"
            "    let f: unsafe extern \"system\" fn({argtypes}) -> usize = core::mem::transmute(p);\n"
            "    f({call})\n"
            "}}\n".format(name=name, params=params, dll=wide(dll), fnname=narrow(name),
                           argtypes=", ".join(["usize"] * n), call=call))

    pairs = []
    for name, dll, _a, _r in sorted(sigs):
        if name in own:
            continue
        if (dll, name) in pairs:
            continue
        pairs.append((dll, name))

    table = ["const API_TABLE: &[(*const u16, *const u8)] = &["]
    for dll, name in pairs:
        table.append("    (%s.as_ptr(), %s.as_ptr())," % (wide(dll), narrow(name)))
    table.append("];")

    probe = '''
/// Walk every (API set, function) pair this DLL would use and report the ones that do not
/// resolve - **without calling any of them**.
///
/// This exists because a lazy resolver is useless as a diagnostic when the first call is what
/// crashes: you never get to read the failure. Walking the table up front turns "it crashed" into
/// "these three functions are missing, here are their names".
#[no_mangle]
pub unsafe extern "system" fn wp81_probe_api_sets(dll_out: *mut *const u16,
                                                  fn_out: *mut *const u8) -> u32 {
    let mut failures = 0u32;
    let mut first = true;
    for (d, n) in API_TABLE.iter().copied() {
        let h = LoadLibraryExW(d, core::ptr::null_mut(), 0);
        let bad = h.is_null() || GetProcAddress(h, n).is_null();
        if bad {
            failures += 1;
            if first {
                if !dll_out.is_null() { *dll_out = d; }
                if !fn_out.is_null() { *fn_out = n; }
                first = false;
            }
        }
    }
    failures
}
'''

    out = HEADER + "\n".join(body) + "\n" + "\n".join(table) + "\n" + probe + FOOTER
    if args.check:
        print("would write %d bytes to %s" % (len(out), OUT))
        return 0

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="") as f:
        f.write(out)
    print("wrote %s (%d bytes, %d trampolines)" % (OUT, len(out), len(seen)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
